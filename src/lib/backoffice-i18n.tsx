type LocaleContextValue = {
  locale: BackofficeLocale;
  setLocale: (locale: BackofficeLocale) => void;
  t: (key: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function BackofficeLocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<BackofficeLocale>("nl-BE");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored !== "nl-BE" && stored !== "en-BE" && stored !== "ar") return;
    const timer = window.setTimeout(() => setLocaleState(stored), 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    const direction = locale === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
    document.body.dir = direction;
  }, [locale]);

  const setLocale = (next: BackofficeLocale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };

  const value = useMemo(() => ({ locale, setLocale, t: (key: string) => translations[locale][key] ?? translations["en-BE"][key] ?? key }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useBackofficeLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useBackofficeLocale must be used inside BackofficeLocaleProvider");
  return context;
}
